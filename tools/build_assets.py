# --------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------
def save_jpg(im: Image.Image, path: Path, size: int | tuple[int, int] | None = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    im = im.convert("RGB")
    if isinstance(size, int):
        im = im.resize((size, size), Image.LANCZOS)
    elif size:
        im = cover(im, size)
    im.save(path, quality=84, optimize=True, progressive=True)


def cover(im: Image.Image, size: tuple[int, int], anchor=(0.5, 0.5)) -> Image.Image:
    """Resize and crop so the image fills `size`, like CSS object-fit: cover."""
    tw, th = size
    scale = max(tw / im.width, th / im.height)
    im = im.resize((round(im.width * scale), round(im.height * scale)), Image.LANCZOS)
    left = round((im.width - tw) * anchor[0])
    top = round((im.height - th) * anchor[1])
    return im.crop((left, top, left + tw, top + th))


def mosaic(tiles: list[Image.Image], size=THUMB_SIZE, gap=4) -> Image.Image:
    """2x2 grid of tiles on a white background."""
    w, h = size
    cw, ch = (w - gap) // 2, (h - gap) // 2
    out = Image.new("RGB", size, "white")
    for k, t in enumerate(tiles[:4]):
        out.paste(cover(t, (cw, ch)), ((k % 2) * (cw + gap), (k // 2) * (ch + gap)))
    return out


def crop_box(im: Image.Image, box, scale=1.0, inset=0) -> Image.Image:
    """Crop with coordinates measured on a scaled preview of the figure."""
    x0, y0, x1, y1 = (round(v * scale) for v in box)
    return im.crop((x0 + inset, y0 + inset, x1 - inset, y1 - inset))


def paper_figure(key: str) -> Image.Image:
    CACHE.mkdir(parents=True, exist_ok=True)
    url = FIGURES[key]
    path = CACHE / f"{key}{Path(url).suffix}"
    if not path.exists():
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        path.write_bytes(urllib.request.urlopen(req, timeout=60).read())
    im = Image.open(path)
    if im.mode in ("RGBA", "LA", "P"):  # transparent figures go on white, not black
        im = im.convert("RGBA")
        bg = Image.new("RGBA", im.size, "white")
        im = Image.alpha_composite(bg, im)
    return im.convert("RGB")


def pdf_clip(pdf: Path, rect, zoom=4.0) -> Image.Image:
    page = pymupdf.open(pdf)[0]
    pix = page.get_pixmap(matrix=pymupdf.Matrix(zoom, zoom), clip=pymupdf.Rect(*rect))
    return Image.open(io.BytesIO(pix.tobytes("png"))).convert("RGB")


