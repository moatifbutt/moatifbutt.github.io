"""Build every image the website uses from the original paper figures.

All demo images and publication thumbnails are cropped from figures that
already exist in the papers (local LaTeX sources, the arXiv HTML versions, or
the publisher's figure files for open-access papers).
Nothing is generated by a model. Re-run this script whenever a source figure
changes; outputs are overwritten in place.

    python3 -m pip install pillow pymupdf
    python3 tools/build_assets.py

Outputs
    assets/demos/<project>/...           images for the interactive project pages
    assets/img/publication_preview/*.jpg thumbnails used by _bibliography/papers.bib
    _data/demos/numcolor.yml             hex -> images table for the NumColor demo
"""

