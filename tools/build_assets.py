def build_arxiv_thumbs() -> None:
    for key, (frac, anchor) in THUMB_CROPS.items():
        im = paper_figure(key)
        w, h = im.size
        im = im.crop((round(frac[0] * w), round(frac[1] * h), round(frac[2] * w), round(frac[3] * h)))
        save_jpg(cover(im, THUMB_SIZE, anchor), THUMBS / f"{key}.jpg")
    for key, boxes in THUMB_TILES.items():
        fig = paper_figure(key)
        save_jpg(mosaic([fig.crop(b) for b in boxes]), THUMBS / f"{key}.jpg")


