# GenColorBench (CVPR 2026): 16 judged examples (prompts live in _data/demos)
# --------------------------------------------------------------------------
GCB_COLS = (17, 302, 595, 881)  # approximate left edge of the image frame in each card column (pt)
GCB_ROWS = (24, 176, 328, 480)  # approximate top edge of each card row (pt)


def build_gencolorbench() -> None:
    # Each image sits in a drawn square frame; the frames are not perfectly
    # aligned across cards, so look them up instead of using fixed offsets.
    page = pymupdf.open(GCB_QUAL)[0]
    frames = [d["rect"] for d in page.get_drawings() if 115 < d["rect"].width < 140 and 115 < d["rect"].height < 140]
    out = DEMOS / "gencolorbench"
    k = 0
    for top in GCB_ROWS:
        for left in GCB_COLS:
            k += 1
            near = [r for r in frames if abs(r.x0 - left) < 10 and abs(r.y0 - top) < 10]
            r = min(near, key=lambda r: r.width * r.height)  # inner frame
            im = pdf_clip(GCB_QUAL, (r.x0 + 1.5, r.y0 + 1.5, r.x1 - 1.5, r.y1 - 1.5))
            save_jpg(cover(im, (DEMO_SIZE, DEMO_SIZE)), out / f"q{k:02d}.jpg")
    picks = ["q05", "q06", "q07", "q08"]
    save_jpg(mosaic([Image.open(out / f"{p}.jpg") for p in picks]), THUMBS / "gencolorbench.jpg")


