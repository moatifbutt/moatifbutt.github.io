def build_numcolor() -> None:
    doc = pymupdf.open(NUMCOLOR_QUAL)
    page = doc[0]
    # Images in reading order: sort by row band, then x. Each hex panel is a
    # 2x2 block, panels are laid out 6 per row band.
    info = sorted(page.get_image_info(xrefs=True), key=lambda i: i["bbox"][1])
    lines: list[list] = []
    for i in info:  # bucket into rows; tops within the same row differ by up to 1 pt
        if lines and abs(lines[-1][0]["bbox"][1] - i["bbox"][1]) < 5:
            lines[-1].append(i)
        else:
            lines.append([i])
    lines = [sorted(r, key=lambda i: i["bbox"][0]) for r in lines]
    assert len(lines) == 10 and all(len(r) == 12 for r in lines), "unexpected figure layout"

    out = DEMOS / "numcolor"
    table = []
    for band in range(5):
        top, bottom = lines[2 * band], lines[2 * band + 1]
        for p in range(6):
            hex_, cat, objs = NC_GROUPS[band * 6 + p]
            if hex_ is None:
                continue
            block = [top[2 * p], top[2 * p + 1], bottom[2 * p], bottom[2 * p + 1]]
            names = objs.split()
            files = []
            for img, obj in zip(block, names):
                pix = pymupdf.Pixmap(doc, img["xref"])
                im = Image.open(io.BytesIO(pix.tobytes("png")))
                fname = f"{hex_[1:].lower()}_{obj}.jpg"
                save_jpg(im, out / fname, DEMO_SIZE)
                files.append({"object": obj, "file": fname})
            table.append({"hex": hex_, "category": cat, "images": files})

    yml = ["# Generated by tools/build_assets.py from the NumColor qualitative figure. Do not edit by hand."]
    for g in table:
        yml.append(f'- hex: "{g["hex"]}"')
        yml.append(f"  category: {g['category']}")
        yml.append("  images:")
        for f in g["images"]:
            yml.append(f"    - {{ object: {f['object']}, file: {f['file']} }}")
    path = SITE / "_data" / "demos" / "numcolor.yml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(yml) + "\n")

    picks = ["fa9217_teddybear", "f9110f_teddybear", "33cc66_teddybear", "1fafb4_couch"]
    save_jpg(mosaic([Image.open(out / f"{p}.jpg") for p in picks]), THUMBS / "numcolor.jpg")


